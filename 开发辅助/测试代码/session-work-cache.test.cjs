'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { SessionWorkCache } = require('../../src/session-work-cache.cjs');
const { readVisibility, saveVisibility } = require('../../src/visibility-preference.cjs');
test('Session cache survives root changes and cleanup preserves projects and other sessions', async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'work-cache-'));
  let selectedRoot = path.join(root, 'default');
  const cache = new SessionWorkCache(() => selectedRoot);
  const other = new SessionWorkCache(() => selectedRoot);
  await cache.set('third|full', { entries: ['third'] });
  await other.set('other|full', { entries: ['other'] });
  selectedRoot = path.join(root, 'chosen');
  await fs.mkdir(path.join(selectedRoot, '用户项目'), { recursive: true });
  await fs.writeFile(path.join(selectedRoot, '用户项目', '作品.txt'), 'keep');
  await cache.set('sixth|full', { entries: ['sixth'] });
  assert.deepEqual(await cache.get('third|full'), { entries: ['third'] });
  assert.deepEqual(await cache.get('sixth|full'), { entries: ['sixth'] });
  const owned = [...cache.directories];
  await cache.close();
  for (const dir of owned) await assert.rejects(fs.stat(dir), { code: 'ENOENT' });
  assert.equal(await fs.readFile(path.join(selectedRoot, '用户项目', '作品.txt'), 'utf8'), 'keep');
  assert.deepEqual(await other.get('other|full'), { entries: ['other'] });
  await cache.set('late', {});
  assert.equal(await cache.get('third|full'), null);
  await other.close();
});
test('Closing during an unfinished cache write waits for it and removes the owned directory', async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'work-cache-close-'));
  const cache = new SessionWorkCache(() => root);
  const writing = cache.set('work', { prompt: 'x'.repeat(250000) });
  const dirs = [...cache.directories];
  await cache.close();
  await writing;
  for (const dir of dirs) await assert.rejects(fs.stat(dir), { code: 'ENOENT' });
});
test('Platform display defaults on and remembers both off and on across independent reads', async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'visibility-'));
  const file = path.join(root, 'visibility.json');
  assert.equal(readVisibility(file), true);
  await saveVisibility(file, false);
  assert.equal(readVisibility(file), false);
  await saveVisibility(file, true);
  assert.equal(readVisibility(file), true);
  await fs.writeFile(file, '{"visible":"false"}');
  assert.equal(readVisibility(file), true);
});
